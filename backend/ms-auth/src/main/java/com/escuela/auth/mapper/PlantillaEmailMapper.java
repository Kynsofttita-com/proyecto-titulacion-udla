package com.escuela.auth.mapper;

import com.escuela.auth.dto.CreatePlantillaEmailRequest;
import com.escuela.auth.dto.PlantillaEmailResponse;
import com.escuela.auth.dto.UpdatePlantillaEmailRequest;
import com.escuela.auth.entity.PlantillaEmail;
import org.mapstruct.BeanMapping;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;
import org.mapstruct.NullValuePropertyMappingStrategy;

@Mapper(componentModel = "spring",
        nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
public interface PlantillaEmailMapper {

    PlantillaEmailResponse toResponse(PlantillaEmail entity);

    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "deletedAt", ignore = true)
    PlantillaEmail toEntity(CreatePlantillaEmailRequest request);

    @BeanMapping(nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "deletedAt", ignore = true)
    void updateEntity(UpdatePlantillaEmailRequest request, @MappingTarget PlantillaEmail entity);
}
